-- Additive upgrade for accounts deployed before CORE.AUTHORIZATION's current
-- SPEC contract. Preserve the legacy columns and records for auditability.
ALTER TABLE SAARTHI.CORE.AUTHORIZATION ADD COLUMN IF NOT EXISTS patient_id VARCHAR;
ALTER TABLE SAARTHI.CORE.AUTHORIZATION ADD COLUMN IF NOT EXISTS scheme VARCHAR;
ALTER TABLE SAARTHI.CORE.AUTHORIZATION ADD COLUMN IF NOT EXISTS package_display VARCHAR;
ALTER TABLE SAARTHI.CORE.AUTHORIZATION ADD COLUMN IF NOT EXISTS letter_status VARCHAR;
ALTER TABLE SAARTHI.CORE.AUTHORIZATION ADD COLUMN IF NOT EXISTS decided_at TIMESTAMP_NTZ;
ALTER TABLE SAARTHI.CORE.AUTHORIZATION ADD COLUMN IF NOT EXISTS expires_at TIMESTAMP_NTZ;
ALTER TABLE SAARTHI.CORE.AUTHORIZATION ADD COLUMN IF NOT EXISTS reviewed_by VARCHAR;

-- Coverage is an identity-keyed relationship; never infer identity from names.
UPDATE SAARTHI.CORE.AUTHORIZATION a
SET patient_id = c.patient_id
FROM SAARTHI.CORE.COVERAGE c
WHERE a.coverage_id = c.coverage_id AND a.patient_id IS NULL;
