def skills_upload_sql() -> str:
    """One COPY INTO per SKILL.md (SINGLE file, no PUT, so deployment stays reproducible from SQL alone).

    Markdown is embedded as a single-quoted literal (backslash and quote escaped) so the same text can be pasted
    into a worksheet. Never executed against Snowflake in this repo: `unverified-needs-deploy`.
    """
    out = ["-- GENERATED by backend/scripts/build_deploy_bundle.py from backend/skills/*/SKILL.md. Do not edit; rebuild instead.",
           "-- Loads the 4 skill definitions to @SAARTHI.STAGES.SKILLS/<skill-name>/SKILL.md. The agent references the FOLDER, not the file.",
           "-- Status: unverified-needs-deploy (COPY INTO ... SINGLE=TRUE path behaviour not yet run on this account).", ""]
    for name in SKILL_NAMES:
        text = (SKILLS_DIR / name / "SKILL.md").read_text()
        assert "$$" not in text, name
        lit = text.replace("\\", "\\\\").replace("'", "''")
        out.append(f"COPY INTO @SAARTHI.STAGES.SKILLS/{name}/SKILL.md\nFROM (SELECT '{lit}')\n"
                   "FILE_FORMAT = (TYPE = CSV, COMPRESSION = NONE, RECORD_DELIMITER = NONE, FIELD_DELIMITER = NONE)\n"
                   "SINGLE = TRUE OVERWRITE = TRUE;\n")
    out.append("-- VERIFY: expect 4 files, one per skill folder.\nLIST @SAARTHI.STAGES.SKILLS;\n")
    return "\n".join(out)


def _semantic_view_guarded() -> str:
    """The view is created inside a handler: a rejected AI_VERIFIED_QUERIES / AI_QUESTION_CATEGORIZATION clause
    (syntax not yet run live) must not stop Run all; the previous view stays in place and the result says so."""
    text = _read("semantic/01_semantic_view.sql")
    stmt = text[text.index("CREATE OR REPLACE SEMANTIC VIEW"):].rstrip()
    assert "$$" not in stmt
    return ("-- ===== BEGIN semantic/01_semantic_view.sql (guarded) =====\n"
            "EXECUTE IMMEDIATE $$\nBEGIN\n" + stmt + "\n"
            "    RETURN 'created: SAARTHI_SEMANTIC_VIEW (with 7 verified queries)';\nEXCEPTION\n    WHEN OTHER THEN\n"
            "        RETURN 'skipped SAARTHI_SEMANTIC_VIEW (previous view kept; clause syntax unverified): ' || SQLERRM;\nEND;\n$$;\n"
            "-- ===== END semantic/01_semantic_view.sql (guarded) =====\n")


def _verify_procs(names: list[str]) -> str:
    listed = ", ".join(f"'{n.upper()}'" for n in names)
    return ("-- VERIFY: expect one row per name, CREATED just now.\n"
            "SELECT procedure_name, created FROM SAARTHI.INFORMATION_SCHEMA.PROCEDURES\n"
            f" WHERE procedure_schema = 'OPERATIONAL' AND procedure_name IN ({listed})\n"
            f" ORDER BY 1;  -- expect {len(set(names))} rows\n")


