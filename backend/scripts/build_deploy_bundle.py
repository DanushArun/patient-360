FORBIDDEN = ("setup.sql",)  # never bundled: drops CORE tables


def _read(rel: str) -> str:
    assert not rel.endswith(FORBIDDEN), rel
    return (SQL / rel).read_text()


def _file(rel: str) -> str:
    text = _read(rel)
    return f"-- ===== BEGIN {rel} =====\n{text.rstrip()}\n-- ===== END {rel} =====\n"


def _slice(rel: str, start: str, end: str, include_end: bool = False) -> str:
    text = _read(rel)
    a = text.index(start)
    b = text.index(end, a) + (len(end) if include_end else 0)
    return f"-- ===== BEGIN {rel} (section) =====\n{text[a:b].rstrip()}\n-- ===== END {rel} =====\n"


def _split_at(rel: str, marker: str) -> tuple[str, str]:
    """Return (text before marker, text from marker on) as two labelled sections of one repo file."""
    text = _read(rel)
    i = text.index(marker)
    return (f"-- ===== BEGIN {rel} (procedure part) =====\n{text[:i].rstrip()}\n-- ===== END {rel} (procedure part) =====\n",
            f"-- ===== BEGIN {rel} (task part) =====\n{text[i:].rstrip()}\n-- ===== END {rel} (task part) =====\n")


def _grants() -> tuple[str, str]:
    """03_grants.sql split so the unconditional grants run first and the AGENT/MCP grants are guarded."""
    text = _read("governance/03_grants.sql")
    marker = "-- Agent + MCP server access."
    i = text.index(marker)
    main = f"-- ===== BEGIN governance/03_grants.sql (section) =====\n{text[:i].rstrip()}\n-- ===== END governance/03_grants.sql (section) =====\n"
    comment = text[i:text.index("REVOKE USAGE ON AGENT")].rstrip()
    guarded = [f"-- ===== BEGIN governance/03_grants.sql (agent/mcp, guarded) =====\n{comment}\n"
               "-- N4-01: the bundle does not create the agent or the MCP server. A missing object must not stop\n"
               "-- Run all; the block returns 'skipped ...' (read the result) and the grant is re-run after the object exists.\n"]
    for kind, name in (("AGENT", "SAARTHI_AGENT"), ("MCP SERVER", "SAARTHI_MCP")):
        verb, direction = ("REVOKE", "FROM") if kind == "AGENT" else ("GRANT", "TO")
        guarded.append(
            "EXECUTE IMMEDIATE $$\nBEGIN\n"
            f"    {verb} USAGE ON {kind} SAARTHI.OPERATIONAL.{name} "
            f"{direction} ROLE SAARTHI_APP;\n"
            f"    RETURN '{verb.lower()}: {name}';\nEXCEPTION\n    WHEN OTHER THEN\n"
            f"        RETURN 'skipped {name} (object absent or not grantable): ' || SQLERRM;\nEND;\n$$;\n")
    guarded.append("-- ===== END governance/03_grants.sql (agent/mcp, guarded) =====\n")
    return main, "\n".join(guarded)


def _generated_documents() -> str:
    from backend.scripts.prepare_synthetic_documents import prepare
    if not MANIFEST.exists():
        raise SystemExit("missing data/generated/cohort_document_manifest.json: run "
                         "`./venv/bin/python -m data.generator.cohort_documents --manifest "
                         "data/generated/cohort_document_manifest.json`")
    records = json.loads(MANIFEST.read_text())
    sql = prepare(records, PDF_DIR)
    # prepare() emits its own USE ROLE header; the bundle header already sets context.
    body = "\n".join(line for line in sql.splitlines()
                     if not line.startswith(("USE ROLE", "USE SECONDARY", "-- Synthetic cohort")))
    digest = hashlib.sha256(MANIFEST.read_bytes()).hexdigest()[:12]
    return (f"-- ===== BEGIN generated cohort documents ({len(records)} documents, manifest sha256 "
            f"{digest}) =====\n{body}\n-- ===== END generated cohort documents =====\n")


