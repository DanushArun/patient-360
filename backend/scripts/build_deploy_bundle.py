def build() -> dict[str, str]:
    files: dict[str, str] = {}
    for name, title, parts in steps():
        header = HEADER.format(name=name, title=title)
        files[name] = header + "\n" + "\n".join(parts).rstrip() + "\n"
    files["README.md"] = readme(files)
    return files


