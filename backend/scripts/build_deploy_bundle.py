def main(argv: list[str]) -> int:
    files = build()
    if "--check" in argv:
        stale = [n for n, text in files.items()
                 if not (OUT / n).exists() or (OUT / n).read_text() != text]
        if not SKILLS_SQL.exists() or SKILLS_SQL.read_text() != skills_upload_sql():
            stale.append("backend/skills/upload_skills.sql")
        extra = [p.name for p in OUT.glob("*") if p.name not in files] if OUT.exists() else []
        if stale or extra:
            print("deploy bundle is stale: " + ", ".join(stale + extra), file=sys.stderr)
            return 1
        print(f"deploy bundle is current ({len(files)} files)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*"):
        if old.name not in files:
            old.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text)
    SKILLS_SQL.write_text(skills_upload_sql())
    print(f"wrote {len(files)} files to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
